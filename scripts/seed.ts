/* 展开为 zh / en 双语条目 */
function expandPack(pack: (typeof PACKS)[number]) {
  const items: {
    id: string;
    pack_id: string;
    title: string;
    url: string;
    category: string;
    lang: string;
    description: string;
  }[] = [];
  for (const [idx, s] of pack.sites.entries()) {
    const base = `${pack.id}-${String(idx).padStart(2, "0")}`;
    items.push({
      id: `${base}-zh`,
      pack_id: pack.id,
      title: s.zh,
      url: s.u,
      category: s.c,
      lang: "zh",
      description: "",
    });
    items.push({
      id: `${base}-en`,
      pack_id: pack.id,
      title: s.en,
      url: s.u,
      category: s.c,
      lang: "en",
      description: "",
    });
  }
  return items;
}

function seedNavpacks() {
  let totalItems = 0;
  for (const pack of PACKS) {
    const items = expandPack(pack);
    totalItems += items.length;
    const ts = now();
    const existing = rows<{ id: string }>("SELECT id FROM navpacks WHERE id = ?", pack.id);
    if (!existing.length) {
      run(
        "INSERT INTO navpacks(id, name, source, url, installed_at, updated_at) VALUES(?,?,?,?,NULL,?)",
        pack.id,
        pack.name,
        "official",
        null,
        ts,
      );
    } else {
      run("UPDATE navpacks SET name=?, updated_at=? WHERE id=?", pack.name, ts, pack.id);
    }
    run("DELETE FROM navpack_items WHERE pack_id = ?", pack.id);
    for (const it of items) {
      run(
        `INSERT INTO navpack_items(id, pack_id, title, url, category, lang, description)
         VALUES(?,?,?,?,?,?,?)`,
        it.id,
        it.pack_id,
        it.title,
        it.url,
        it.category,
        it.lang,
        it.description,
      );
    }
  }
  console.log(`✔ 导航包 ${PACKS.length} 个，条目 ${totalItems} 条`);
}

